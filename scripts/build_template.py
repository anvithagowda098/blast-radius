"""Build switch/blast-radius.template.yaml from template.base.yaml + switch/agents/*.md.

The agent instruction files stay the single source; this pastes each one into
the template where the base has an `@@name@@` line, indented to fit.

    python scripts/build_template.py           # write the template
    python scripts/build_template.py --check   # exit 1 if the template is stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

SWITCH = Path(__file__).resolve().parent.parent / "switch"
BASE = SWITCH / "template.base.yaml"
OUT = SWITCH / "blast-radius.template.yaml"
MARKER = re.compile(r"^(?P<indent>[ ]*)@@(?P<name>[a-z]+)@@\n", re.MULTILINE)
HEADER = "# GENERATED by scripts/build_template.py: edit switch/template.base.yaml and switch/agents/*.md instead.\n"


def render() -> str:
    base = BASE.read_text(encoding="utf-8")
    base = "".join(line for line in base.splitlines(keepends=True) if not line.startswith("#:"))

    def paste(match: re.Match) -> str:
        text = (SWITCH / "agents" / f"{match['name']}.md").read_text(encoding="utf-8")
        indent = match["indent"]
        return "".join(indent + line if line.strip() else "\n" for line in text.splitlines(keepends=True))

    return HEADER + MARKER.sub(paste, base)


def main(argv: list[str]) -> int:
    rendered = render()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != rendered:
            print(f"{OUT} is stale: run python scripts/build_template.py", file=sys.stderr)
            return 1
        return 0
    with OUT.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(rendered)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
